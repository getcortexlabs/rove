#!/usr/bin/env python3
"""Generate fixed benchmark and test inputs from archived BEAST states and a known seed."""

import argparse
import json
import math
from decimal import Decimal, localcontext
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "benchmarks/beast-2.7.8/2026-10-25"
SNAPSHOT = REFERENCE / "snapshot-20261025.json"
SNAPSHOTS = [SNAPSHOT, REFERENCE / "snapshot-20261026.json"]


def postorder_tree(state):
    """Child pairs, branch distances and node heights, with tips first and
    parents after children."""
    nodes = {node["index"]: node for node in state["nodes"]}
    order = list(range(len(state["taxa"])))
    visited = set()

    def visit(index):
        assert index not in visited, "tree has repeated nodes"
        visited.add(index)
        for child in nodes[index]["children"]:
            visit(child)
        if nodes[index]["children"]:
            order.append(index)

    visit(state["root"])
    assert visited == set(nodes)
    assert [nodes[i]["taxon"] for i in order[:len(state["taxa"])]] == state["taxa"]
    remap = {old: new for new, old in enumerate(order)}
    parents = {child: node for node in nodes.values() for child in node["children"]}
    children = []
    distances = []
    heights = []
    for index in order:
        node = nodes[index]
        pair = node["children"]
        assert len(pair) in (0, 2)
        children.append((remap[pair[0]], remap[pair[1]]) if pair else None)
        distance = 0.0 if index == state["root"] else (
            parents[index]["height"] - node["height"]
        ) * node["branch_rate"]
        assert distance >= 0
        distances.append(float(distance))
        heights.append(float(node["height"]))
    return children, distances, heights


def rust_children(children):
    items = ["None" if pair is None else f"Some(({pair[0]}, {pair[1]}))" for pair in children]
    return "&[" + ", ".join(items) + "]"


def exact_log_likelihoods(state, children, distances):
    """Each pattern's log likelihood, keyed by its states, from the same double
    inputs as the tests but evaluated with 60 significant digits."""
    with localcontext() as context:
        context.prec = 60
        frequencies = [Decimal(f) for f in state["frequencies"]]
        states = range(len(frequencies))
        normalization = 1 - sum(f * f for f in frequencies)
        matrices = []
        for distance in distances:
            matrices.append([])
            for rate in state["category_rates"]:
                stay = (-Decimal(distance) * Decimal(rate) / normalization).exp()
                matrices[-1].append([[f * (1 - stay) + (stay if i == j else 0)
                                      for j, f in enumerate(frequencies)] for i in states])
        result = {}
        for pattern in state["patterns"]:
            likelihood = Decimal(0)
            for category, weight in enumerate(state["category_weights"]):
                partials = []
                for node, pair in enumerate(children):
                    if pair is None:
                        partials.append([Decimal(1 if pattern["states"][node] == s else 0) for s in states])
                        continue
                    below = [
                        [sum(row[j] * partials[child][j] for j in states)
                         for row in matrices[child][category]]
                        for child in pair
                    ]
                    partials.append([x * y for x, y in zip(*below)])
                likelihood += Decimal(weight) * sum(f * x for f, x in zip(frequencies, partials[-1]))
            result[tuple(pattern["states"])] = likelihood.ln()
        return result


def reference_source():
    state = json.loads(SNAPSHOT.read_text())
    children, distances, _ = postorder_tree(state)
    observed = math.fsum(p["weight"] * p["log_likelihood"] for p in state["patterns"])
    assert sum(p["weight"] for p in state["patterns"]) == 50
    lines = [
        "// Generated by tools/benchmarks/prepare.py from snapshot-20261025.json.",
        "// EXPECTED is the observed Mk likelihood without the zero-weight ascertainment",
        "// patterns; EXPECTED_MKV is the XML's likelihood conditioned on variable characters.",
        "pub const TAXA: &[&str] = &[" + ", ".join(json.dumps(t) for t in state["taxa"]) + "];",
        "pub const CHILDREN: &[Option<(usize, usize)>] = " + rust_children(children) + ";",
        f"pub const DISTANCES: &[f64] = &{distances!r};",
        f"pub const RATES: &[f64] = &{state['category_rates']!r};",
        f"pub const CATEGORY_WEIGHTS: &[f64] = &{state['category_weights']!r};",
        f"pub const FREQUENCIES: &[f64] = &{state['frequencies']!r};",
        f"pub const EXPECTED: f64 = {observed!r};",
        f"pub const EXPECTED_MKV: f64 = {float(state['distributions']['likelihood'])!r};",
    ]
    # rustfmt is deliberately skipped for the generated numeric fixture.
    return "\n".join(lines) + "\n"


def states_source():
    """Both final BEAST states, with the Mkv values the tests must reproduce."""
    states = [json.loads(path.read_text()) for path in SNAPSHOTS]
    taxa = states[0]["taxa"]
    lines = [
        "// Generated by tools/benchmarks/prepare.py from the archived BEAST 2.7.8 snapshots.",
        "// Pattern log likelihoods are unconditioned. Weight-zero patterns are the constant Mkv patterns.",
        "// Exact values use the same double inputs, evaluated with 60 significant digits.",
        "pub struct Pattern {",
        "    pub states: &'static [u8],",
        "    pub weight: usize,",
        "    pub log_likelihood: f64,",
        "    pub exact_log_likelihood: f64,",
        "}",
        "pub struct State {",
        "    pub seed: u64,",
        "    pub children: &'static [Option<(usize, usize)>],",
        "    pub distances: &'static [f64],",
        "    pub rates: &'static [f64],",
        "    pub category_weights: &'static [f64],",
        "    pub frequencies: &'static [f64],",
        "    pub patterns: &'static [Pattern],",
        "    pub log_variable_probability: f64,",
        "    pub log_likelihood: f64,",
        "    pub exact_log_variable_probability: f64,",
        "    pub exact_log_likelihood: f64,",
        "    pub heights: &'static [f64],",
        "    pub birth_difference: f64,",
        "    pub relative_death: f64,",
        "    pub birth_death: f64,",
        "}",
        "pub const TAXA: &[&str] = &[" + ", ".join(json.dumps(t) for t in taxa) + "];",
        "pub const STATES: &[State] = &[",
    ]
    for path, state in zip(SNAPSHOTS, states):
        assert state["taxa"] == taxa
        assert sum(p["weight"] for p in state["patterns"]) == 50
        constant = [p["states"] for p in state["patterns"] if p["weight"] == 0]
        assert constant == [[s] * len(taxa) for s in range(len(state["frequencies"]))]
        children, distances, heights = postorder_tree(state)
        assert all(height == 0 for height in heights[:len(taxa)])
        exact = exact_log_likelihoods(state, children, distances)
        with localcontext() as context:
            context.prec = 60
            correction = (1 - sum(exact[tuple(states)].exp() for states in constant)).ln()
            observed = sum(p["weight"] * exact[tuple(p["states"])] for p in state["patterns"])
            conditioned = observed - sum(p["weight"] for p in state["patterns"]) * correction
        patterns = ", ".join(
            f"Pattern {{ states: &{p['states']!r}, weight: {p['weight']}, "
            f"log_likelihood: {float(p['log_likelihood'])!r}, "
            f"exact_log_likelihood: {float(exact[tuple(p['states'])])!r} }}"
            for p in state["patterns"]
        )
        lines += [
            "    State {",
            f"        seed: {path.stem.split('-')[1]},",
            "        children: " + rust_children(children) + ",",
            f"        distances: &{distances!r},",
            f"        rates: &{state['category_rates']!r},",
            f"        category_weights: &{state['category_weights']!r},",
            f"        frequencies: &{state['frequencies']!r},",
            f"        patterns: &[{patterns}],",
            f"        log_variable_probability: {float(state['log_ascertainment_correction'])!r},",
            f"        log_likelihood: {float(state['distributions']['likelihood'])!r},",
            f"        exact_log_variable_probability: {float(correction)!r},",
            f"        exact_log_likelihood: {float(conditioned)!r},",
            f"        heights: &{heights!r},",
            f"        birth_difference: {float(state['parameters']['BDBirthRate.t:matriz_20x50'][0])!r},",
            f"        relative_death: {float(state['parameters']['BDDeathRate.t:matriz_20x50'][0])!r},",
            f"        birth_death: {float(state['distributions']['BirthDeath.t:matriz_20x50'])!r},",
            "    },",
        ]
    lines.append("];")
    return "\n".join(lines) + "\n"


class SplitMix64:
    def __init__(self, seed):
        self.state = seed

    def uniform(self):
        mask = (1 << 64) - 1
        self.state = (self.state + 0x9E3779B97F4A7C15) & mask
        value = self.state
        value = ((value ^ (value >> 30)) * 0xBF58476D1CE4E5B9) & mask
        value = ((value ^ (value >> 27)) * 0x94D049BB133111EB) & mask
        value ^= value >> 31
        return (value >> 11) / (1 << 53)


def matrix_90x250():
    """Simulate binary Mk on a balanced tree; retain constant columns as observed."""
    rng = SplitMix64(20261026)
    rows = [[] for _ in range(90)]

    def evolve(start, end, state):
        if end - start == 1:
            rows[start].append(str(state))
            return
        middle = (start + end) // 2
        for left, right in [(start, middle), (middle, end)]:
            stay = (1 + math.exp(-2 * 0.1)) / 2
            child_state = state if rng.uniform() < stay else 1 - state
            evolve(left, right, child_state)

    for _ in range(250):
        evolve(0, 90, int(rng.uniform() >= 0.5))
    lines = [
        "#NEXUS",
        "[Binary Mk simulation; SplitMix64 seed 20261026; balanced tree; branch distance 0.1.]",
        "[250 independent characters, including constants; no ascertainment filtering.]",
        "BEGIN DATA;",
        "  DIMENSIONS NTAX=90 NCHAR=250;",
        '  FORMAT DATATYPE=STANDARD SYMBOLS="01" MISSING=?;',
        "  MATRIX",
    ]
    lines.extend(f"  T{i + 1}  {''.join(row)}" for i, row in enumerate(rows))
    return "\n".join(lines + ["  ;", "END;", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        ROOT / "benches/support/reference_state.rs": reference_source(),
        ROOT / "fixtures/benchmarks/morphology_90x250.nex": matrix_90x250(),
        ROOT / "tests/support/reference_states.rs": states_source(),
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"stale generated fixture: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
